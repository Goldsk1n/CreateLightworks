package com.goldskinmc.lightworks.registry;

import static com.goldskinmc.lightworks.Lightworks.REGISTRATE;

import com.simibubi.create.AllBlocks;
import com.simibubi.create.AllItems;
import com.tterrag.registrate.providers.ProviderType;
import com.tterrag.registrate.providers.RegistrateRecipeProvider;
import net.minecraft.advancements.critereon.InventoryChangeTrigger;
import net.minecraft.data.recipes.RecipeCategory;
import net.minecraft.data.recipes.ShapedRecipeBuilder;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.ItemTags;
import net.minecraft.tags.TagKey;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.ItemLike;
import net.neoforged.neoforge.common.Tags;

/**
 * Shaped crafting recipes, all built around Create's Electron Tube: brass for the precise beam lights,
 * andesite and iron for vehicle lamps. Generated by {@code runData}; common tags where Create uses them.
 */
public final class LightworksRecipes {
    private static final TagKey<Item> GLASS = Tags.Items.GLASS_BLOCKS_COLORLESS;
    private static final TagKey<Item> BRASS_PLATES = common("plates/brass");
    private static final TagKey<Item> IRON_PLATES = common("plates/iron");

    private LightworksRecipes() {
    }

    public static void register() {
        REGISTRATE.addDataGenerator(ProviderType.RECIPE, LightworksRecipes::recipes);
    }

    private static void recipes(RegistrateRecipeProvider out) {
        shaped(LightworksBlocks.SEARCHLIGHT, 1, " G ", "PTP", " C ")
                .define('G', GLASS).define('P', BRASS_PLATES).define('T', AllItems.ELECTRON_TUBE)
                .define('C', AllBlocks.BRASS_CASING)
                .save(out);
        shaped(LightworksBlocks.FLOODLIGHT, 1, "GGG", "PTP", " C ")
                .define('G', GLASS).define('P', BRASS_PLATES).define('T', AllItems.ELECTRON_TUBE)
                .define('C', AllBlocks.BRASS_CASING)
                .save(out);
        shaped(LightworksBlocks.PAN_TILT_HEAD, 1, " P ", "WCW", " S ")
                .define('P', BRASS_PLATES).define('W', AllBlocks.COGWHEEL).define('C', AllBlocks.BRASS_CASING)
                .define('S', AllBlocks.SHAFT)
                .save(out);
        shaped(LightworksBlocks.ROTATING_BEACON, 1, "GGG", "GTG", " C ")
                .define('G', GLASS).define('T', AllItems.ELECTRON_TUBE).define('C', AllBlocks.BRASS_CASING)
                .save(out);
        shaped(LightworksBlocks.HEADLIGHT, 2, " G ", "ITI", " A ")
                .define('G', GLASS).define('I', IRON_PLATES).define('T', AllItems.ELECTRON_TUBE)
                .define('A', AllBlocks.ANDESITE_CASING)
                .save(out);
        shaped(LightworksBlocks.WARNING_LIGHT, 2, " G ", "DTD", " I ")
                .define('G', GLASS).define('D', Tags.Items.DYES_ORANGE).define('T', AllItems.ELECTRON_TUBE)
                .define('I', BRASS_PLATES)
                .save(out);
        shaped(LightworksBlocks.TAIL_LIGHT, 2, " G ", "DTD", " I ")
                .define('G', GLASS).define('D', Tags.Items.DYES_RED).define('T', AllItems.ELECTRON_TUBE)
                .define('I', IRON_PLATES)
                .save(out);
        // Red and green either way round (shaped recipes also match mirrored)
        shaped(LightworksBlocks.NAVIGATION_LIGHT, 2, " G ", "RTL", " I ")
                .define('G', GLASS).define('R', Tags.Items.DYES_RED).define('L', Tags.Items.DYES_GREEN)
                .define('T', AllItems.ELECTRON_TUBE).define('I', IRON_PLATES)
                .save(out);
    }

    /** A recipe unlocked by picking up an Electron Tube, which every light needs (and the head's light). */
    private static ShapedRecipeBuilder shaped(ItemLike result, int count, String... rows) {
        ShapedRecipeBuilder builder = ShapedRecipeBuilder.shaped(RecipeCategory.REDSTONE, result, count);
        for (String row : rows) {
            builder.pattern(row);
        }
        return builder.unlockedBy("has_electron_tube",
                InventoryChangeTrigger.TriggerInstance.hasItems(AllItems.ELECTRON_TUBE.get()));
    }

    private static TagKey<Item> common(String path) {
        return ItemTags.create(ResourceLocation.fromNamespaceAndPath("c", path));
    }
}
